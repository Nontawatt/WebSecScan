def _build():
    gname = {g: n for g, n, _ in GROUPS}
    gcsf = {g: c for g, _, c in GROUPS}
    items = []
    main_counter = {}
    sub_counter = {}
    for group, level, text, ref, applies, auto in _ITEMS_RAW:
        if level == "main":
            main_counter[group] = main_counter.get(group, 0) + 1
            sub_counter[(group, main_counter[group])] = 0
            iid = f"{group}.{main_counter[group]}"
            scheme = "comply"
        else:
            mc = main_counter[group]
            sub_counter[(group, mc)] += 1
            iid = f"{group}.{mc}.{sub_counter[(group, mc)]}"
            scheme = "mat3"
        items.append({
            "id": iid, "cat": group, "cat_name": gname[group], "csf": gcsf[group],
            "scheme": scheme, "level": level, "text": text.replace("*", ""),
            "text_md": text, "ref": ref, "applies_to": applies, "auto": auto,
            "otg": "",
        })
    return items


